function seedIdentity(record) {
  return [
    String(record.email1).toLowerCase(),
    record.dispositionStatus,
    new Date(record.dispositionDateTime).getTime(),
  ].join('|');
}

function recordsToCreate(existing, seeds = SEED_RECORDS) {
  const seen = new Set(existing.map(seedIdentity));
  return seeds.filter((record) => !seen.has(seedIdentity(record)));
}

